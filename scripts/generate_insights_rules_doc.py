"""Write docs/insights-rules.md: one table of every registered rule, with an example message built from its own sample.

    DJANGO_SETTINGS_MODULE=finance_tracker.settings python scripts/generate_insights_rules_doc.py
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'finance_tracker.settings')

import django  # noqa: E402

django.setup()

from django.utils import translation  # noqa: E402

from expenses.insights import registry  # noqa: E402

PLAN = {0: 'Free', 1: 'Plus', 2: 'Pro'}
SURFACE = {'dashboard': 'Dashboard', 'module': 'Module page', 'analytics': 'Analytics', 'bell': 'Bell', 'push': 'Push',
           'digest': 'Digest', 'monthly': 'Monthly report', 'year_in_review': 'Year in Review'}


def cell(text: str) -> str:
    return str(text).replace('|', '\\|').replace('\n', ' ')


def main() -> None:
    lines = [
        '# Insight rules', '',
        'Generated by `scripts/generate_insights_rules_doc.py` from the registry; the example is what the rule says on its own',
        'sample (in English). Cost "nightly" rules run in `generate_insights`; "quick" ones may also run when a dashboard visit',
        'finds a person\'s data has changed. See `docs/insights-tone.md` for how every one of them should sound.', '',
        '| id | module | plan | runs | history | facts used | cooldown | surfaces | example (en) |',
        '|---|---|---|---|---|---|---|---|---|',
    ]
    with translation.override('en'):
        for rule in registry.all_rules():
            ctx = rule.sample('en')
            with ctx.declared(rule.needs):
                first = rule.evaluate(ctx)[0]
            surfaces = ', '.join(SURFACE[s.value] for s in sorted(rule.surfaces, key=lambda s: s.value))
            if rule.pool:
                surfaces += ' (Free: one a week)'
            lines.append('| `{}` | {} | {} | {} | {} | {} | {}d | {} | **{}** {} |'.format(
                rule.id, rule.module.value, PLAN[int(rule.min_plan)], 'nightly' if rule.cost == 'heavy' else 'quick',
                f'{rule.min_history} cycles' if rule.min_history else 'none',
                ', '.join(sorted(rule.needs)) or 'none', rule.cooldown_days, surfaces,
                cell(first.title), cell(first.message)))
    (ROOT / 'docs' / 'insights-rules.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
